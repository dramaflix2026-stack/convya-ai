test('default sample sends scripted text after incoming customer message and simulated wait',()=>{
 const f=flow.create();
 assert.equal(f.nodes.length,5);
 assert.deepEqual(flow.validate(f),[]);
 const run=flow.simulate(f,'Oi! Quero conhecer seu serviço.');
 assert.equal(run.ok,true);
 assert.equal(run.waiting,false);
 assert.equal(run.ended,true);
 assert.deepEqual(run.steps.map(s=>s.type),['start','input','wait','text','end']);
 assert.equal(run.events[0].direction,'in');
 assert.equal(run.events[1].direction,'out');
 assert.match(run.events[1].text,/Olá/);
 assert.match(run.steps[2].result,/2 minutos.*acelerado/);
});
