test('visual branches can route yes and no using message content',()=>{
 const f=flow.create();
 const c=flow.node('condition',420,620);
 const yes=flow.node('text',200,850);
 const no=flow.node('text',700,850);
 yes.config.text='Oferta para quem quer SITE';
 no.config.text='Outra orientação';
 const end=f.nodes.find(n=>n.type==='end');
 const before=f.nodes.find(n=>n.type==='text');
 f.nodes.push(c,yes,no);
 flow.connect(f,before.id,'out',c.id);
 flow.connect(f,c.id,'yes',yes.id);
 flow.connect(f,c.id,'no',no.id);
 flow.connect(f,yes.id,'out',end.id);
 flow.connect(f,no.id,'out',end.id);
 assert.deepEqual(flow.validate(f),[]);
 const a=flow.simulate(f,'quero um SITE');
 const b=flow.simulate(f,'quero saber os horários');
 assert.ok(a.events.some(e=>e.text==='Oferta para quem quer SITE'));
 assert.ok(!a.events.some(e=>e.text==='Outra orientação'));
 assert.ok(b.events.some(e=>e.text==='Outra orientação'));
 assert.ok(b.steps.some(e=>/NÃO/.test(e.result)));
});
test('media blocks render only explicit safe URLs in simulation',()=>{
 const f=flow.create(),medium=flow.node('image',360,760);
 medium.config.url='https://example.org/menu.jpg';
 medium.config.caption='Cardápio ilustrativo';
 const msg=f.nodes.find(n=>n.type==='text'),end=f.nodes.find(n=>n.type==='end');
 f.nodes.push(medium);flow.connect(f,msg.id,'out',medium.id);flow.connect(f,medium.id,'out',end.id);
 assert.deepEqual(flow.validate(f),[]);
 const testRun=flow.simulate(f,'oi');
 assert.ok(testRun.events.some(m=>m.type==='image'&&m.url===medium.config.url));
 assert.equal(flow.validUrl('javascript:alert(1)'),false);
 medium.config.url='javascript:alert(1)';
 assert.match(flow.validate(f).join(' '),/URL/i);
});
test('flows cannot publish dangling paths, orphan blocks, broken branches or loops',()=>{
 const f=flow.create();const extra=flow.node('text',500,450);f.nodes.push(extra);
 assert.match(flow.validate(f).join(' '),/desconectado/);
 const msg=f.nodes.find(n=>n.type==='text'),end=f.nodes.find(n=>n.type==='end');
 flow.connect(f,msg.id,'out',extra.id);
 flow.connect(f,extra.id,'out',msg.id);
 assert.match(flow.validate(f).join(' '),/ciclo/);
 assert.throws(()=>flow.connect(f,msg.id,'out',f.nodes[0].id),/início/i);
});
test('human transfer and optional AI are explicitly dry-run only',()=>{
 const f=flow.create();
 const human=flow.node('human',550,750);
 const msg=f.nodes.find(n=>n.type==='text');
 f.nodes=f.nodes.filter(n=>n.type!=='end');f.nodes.push(human);
 flow.connect(f,msg.id,'out',human.id);
 assert.deepEqual(flow.validate(f),[]);
 const result=flow.simulate(f,'Oi');
 assert.equal(result.human,true);
 assert.match(result.events.at(-1).text,/Nenhum atendente|simulada/i);
 assert.ok(!result.events.some(e=>e.type==='whatsapp'));
 const ai=flow.node('ai',540,600);
 f.nodes.push(ai);flow.connect(f,msg.id,'out',ai.id);flow.connect(f,ai.id,'out',human.id);
 const second=flow.simulate(f,'oi');
 assert.ok(second.events.some(e=>/Bloco IA configurado/.test(e.text)));
});
